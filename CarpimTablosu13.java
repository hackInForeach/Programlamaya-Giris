public class CarpimTablosu13 {

    public static void main(String[] args) {

        for (int i = 0; i < 10; i++) {
            for (int j = 0; j < 10; j++) {
                System.out.print((j + 1) + " x " + (i + 1) + " = " + ((i + 1) * (j + 1))+"\t");
            }
            System.out.println("\t");
        }

    }

}
